//! Benchmark registration, command-line handling and the `main` entry point.
//!
//! The `tpt_benchmark::main!` macro expands to a call to [`main`] with a table
//! of [`BenchDef`]s generated from the `#[tpt_bench]` attributes.

use std::io::{self, IsTerminal, Write};
use std::path::{Path, PathBuf};
use std::process::ExitCode;
use std::time::Duration;

use serde::{Deserialize, Serialize};

use crate::baseline::{self, Verdict};
use crate::bencher::Config;
use crate::stats::Summary;
use crate::{json, report};

/// Which measurement layer a benchmark runs under.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[non_exhaustive]
pub enum LayerKind {
    /// Elapsed wall time, nanoseconds per iteration.
    WallClock,
    /// Heap allocation calls per iteration.
    Allocations,
    /// Heap bytes requested per iteration.
    AllocBytes,
    /// Retired CPU instructions per iteration.
    HwInstructions,
    /// L1 data cache misses per iteration.
    HwL1Misses,
    /// L2 cache misses per iteration.
    HwL2Misses,
    /// Mispredicted branches per iteration.
    HwBranchMisses,
}

impl LayerKind {
    /// Display name, also used as the key in baselines and JSON output.
    #[must_use]
    pub const fn name(self) -> &'static str {
        match self {
            Self::WallClock => "WallClock",
            Self::Allocations => "Allocations",
            Self::AllocBytes => "AllocBytes",
            Self::HwInstructions => "HwInstructions",
            Self::HwL1Misses => "HwL1Misses",
            Self::HwL2Misses => "HwL2Misses",
            Self::HwBranchMisses => "HwBranchMisses",
        }
    }
}

/// A registered benchmark, as generated by the `#[tpt_bench]` macros.
#[derive(Clone, Copy, Debug)]
#[non_exhaustive]
pub struct BenchDef {
    /// Module name of the enclosing `#[tpt_bench_group]`, or `""` if none.
    pub group: &'static str,
    /// Benchmark name, including any argument suffix such as `multiply/128`.
    pub name: &'static str,
    /// Layers this benchmark is activated under.
    pub layers: &'static [LayerKind],
    /// Runs the benchmark under one layer. Returns `None` when that layer is
    /// unavailable on this machine (for example hardware counters without
    /// permission); the runner then warns and skips it.
    pub run: fn(LayerKind, &Config) -> Option<Summary>,
}

impl BenchDef {
    /// Builds a definition. The `#[tpt_bench]` macros call this; prefer them
    /// to writing definitions by hand.
    #[must_use]
    pub const fn new(
        group: &'static str,
        name: &'static str,
        layers: &'static [LayerKind],
        run: fn(LayerKind, &Config) -> Option<Summary>,
    ) -> Self {
        Self {
            group,
            name,
            layers,
            run,
        }
    }

    /// The fully qualified name, `group::name`, or just `name` when ungrouped.
    #[must_use]
    pub fn full_name(&self) -> String {
        if self.group.is_empty() {
            self.name.to_owned()
        } else {
            format!("{}::{}", self.group, self.name)
        }
    }
}

/// The measured result of one benchmark: one summary per active layer.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
#[non_exhaustive]
pub struct BenchResult {
    /// Fully qualified benchmark name.
    pub name: String,
    /// One summary per layer that ran.
    pub layers: Vec<Summary>,
}

/// Runs the selected benchmarks and collects their results.
///
/// `progress` receives one line per benchmark and layer, and is typically
/// stderr. Pass `None` to run silently.
pub fn run_benches(
    defs: &[BenchDef],
    config: &Config,
    mut progress: Option<&mut dyn Write>,
) -> Vec<BenchResult> {
    let mut results = Vec::with_capacity(defs.len());
    for def in defs {
        let name = def.full_name();
        let mut layers = Vec::new();
        for &kind in def.layers {
            if let Some(out) = progress.as_deref_mut() {
                let _ = writeln!(out, "Benchmarking {name} [{}]", kind.name());
            }
            match (def.run)(kind, config) {
                Some(summary) => layers.push(summary),
                None => {
                    if let Some(out) = progress.as_deref_mut() {
                        let _ = writeln!(
                            out,
                            "warning: {name} [{}] skipped: layer unavailable on this machine",
                            kind.name()
                        );
                    }
                }
            }
        }
        results.push(BenchResult { name, layers });
    }
    results
}

/// Parsed command-line options.
#[derive(Clone, Debug, Default, PartialEq)]
#[non_exhaustive]
pub struct Options {
    /// Positional filter: run only benchmarks whose name contains this text.
    pub filter: Option<String>,
    /// With `filter`, require an exact name match instead of a substring.
    pub exact: bool,
    /// List benchmark names and exit.
    pub list: bool,
    /// Save the results as a named baseline.
    pub save_baseline: Option<String>,
    /// Compare against a named baseline.
    pub baseline: Option<String>,
    /// Skip HTML report generation.
    pub noplot: bool,
    /// Trade precision for speed: looser CI target and shorter time cap.
    pub quick: bool,
    /// Percentage change that counts as a regression when significant.
    pub threshold_pct: f64,
    /// Show the help text and exit.
    pub help: bool,
}

impl Options {
    /// Parses arguments (excluding the program name).
    ///
    /// # Errors
    ///
    /// Returns a message for unknown flags or missing values.
    pub fn parse<I, S>(args: I) -> Result<Self, String>
    where
        I: IntoIterator<Item = S>,
        S: AsRef<str>,
    {
        let mut opts = Self {
            threshold_pct: 5.0,
            ..Self::default()
        };
        let mut iter = args.into_iter();
        while let Some(arg) = iter.next() {
            let arg = arg.as_ref();
            match arg {
                "--exact" => opts.exact = true,
                "--list" => opts.list = true,
                "--noplot" => opts.noplot = true,
                "--quick" => opts.quick = true,
                "-h" | "--help" => opts.help = true,
                "--save-baseline" => opts.save_baseline = Some(value(&mut iter, arg)?),
                "--baseline" => opts.baseline = Some(value(&mut iter, arg)?),
                "--threshold" => {
                    let raw = value(&mut iter, arg)?;
                    opts.threshold_pct = raw
                        .parse::<f64>()
                        .ok()
                        .filter(|t| t.is_finite() && *t >= 0.0)
                        .ok_or_else(|| format!("invalid --threshold value `{raw}`"))?;
                }
                "--confidence" => {
                    let raw = value(&mut iter, arg)?;
                    if raw != "0.95" {
                        return Err(format!(
                            "unsupported --confidence `{raw}`: only 0.95 is implemented"
                        ));
                    }
                }
                // Cargo passes these when running benches; they are harmless.
                "--bench" => {}
                flag if flag.starts_with('-') => return Err(format!("unknown option `{flag}`")),
                positional => opts.filter = Some(positional.to_owned()),
            }
        }
        Ok(opts)
    }

    /// Whether `name` passes the positional filter.
    #[must_use]
    pub fn selects(&self, name: &str) -> bool {
        match (&self.filter, self.exact) {
            (None, _) => true,
            (Some(f), true) => name == f,
            (Some(f), false) => name.contains(f.as_str()),
        }
    }
}

fn value<I, S>(iter: &mut I, flag: &str) -> Result<String, String>
where
    I: Iterator<Item = S>,
    S: AsRef<str>,
{
    iter.next()
        .map(|v| v.as_ref().to_owned())
        .ok_or_else(|| format!("`{flag}` needs a value"))
}

/// The directory for all generated output: `target/tpt-benchmark/`.
///
/// Honours `CARGO_TARGET_DIR` when it is set, and otherwise uses `target/`
/// relative to the working directory, which is where `cargo bench` runs.
#[must_use]
pub fn output_dir() -> PathBuf {
    let target =
        std::env::var_os("CARGO_TARGET_DIR").map_or_else(|| PathBuf::from("target"), PathBuf::from);
    target.join("tpt-benchmark")
}

/// Entry point for `harness = false` benchmark binaries.
///
/// Parses the command line, runs the selected benchmarks, prints the
/// terminal report, writes the JSON export and the HTML report (unless
/// `--noplot`), saves or compares baselines, and returns a non-zero exit code
/// when a significant regression exceeds the threshold.
pub fn main(defs: &[BenchDef]) -> ExitCode {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let opts = match Options::parse(&args) {
        Ok(opts) => opts,
        Err(message) => {
            eprintln!("error: {message}");
            eprintln!("run with --help for usage");
            return ExitCode::from(2);
        }
    };
    if opts.help {
        print!("{}", HELP);
        return ExitCode::SUCCESS;
    }

    let selected: Vec<BenchDef> = defs
        .iter()
        .copied()
        .filter(|d| opts.selects(&d.full_name()))
        .collect();

    if opts.list {
        for def in &selected {
            println!("{}", def.full_name());
        }
        return ExitCode::SUCCESS;
    }

    let mut config = Config::default();
    if opts.quick {
        config.warmup = Duration::from_millis(20);
        config.engine.rel_error = 0.05;
        config.engine.max_time = Duration::from_secs(1);
    }

    let mut stderr = io::stderr();
    let results = run_benches(&selected, &config, Some(&mut stderr));

    let dir = output_dir();
    let baseline_comparison = match &opts.baseline {
        Some(name) => match baseline::load(&dir, name) {
            Ok(base) => Some(baseline::compare(&results, &base, opts.threshold_pct)),
            Err(err) => {
                eprintln!("error: cannot load baseline `{name}`: {err}");
                return ExitCode::from(2);
            }
        },
        None => None,
    };

    let color = io::stdout().is_terminal() && std::env::var_os("NO_COLOR").is_none();
    print!(
        "{}",
        report::render_terminal(&results, baseline_comparison.as_deref(), color)
    );

    if let Err(err) = json::write(&dir, &results, &crate::environment::Environment::capture()) {
        eprintln!("warning: could not write JSON export: {err}");
    }
    if !opts.noplot {
        if let Err(err) = report::write_html(&dir, &results, baseline_comparison.as_deref()) {
            eprintln!("warning: could not write HTML report: {err}");
        }
    }
    if let Some(name) = &opts.save_baseline {
        if let Err(err) = baseline::save(&dir, name, &results) {
            eprintln!("error: could not save baseline `{name}`: {err}");
            return ExitCode::from(2);
        }
    }

    let regressed = baseline_comparison
        .as_deref()
        .is_some_and(|c| c.iter().any(|c| c.verdict == Verdict::Regressed));
    if regressed {
        eprintln!(
            "error: significant regression above {}%",
            opts.threshold_pct
        );
        return ExitCode::from(1);
    }
    ExitCode::SUCCESS
}

/// Path of a baseline file for `name`.
#[must_use]
pub fn baseline_path(dir: &Path, name: &str) -> PathBuf {
    baseline::path(dir, name)
}

const HELP: &str = "\
USAGE: <bench-binary> [OPTIONS] [FILTER]

ARGS:
    <FILTER>               Run only benchmarks whose name contains FILTER

OPTIONS:
    --exact                Require an exact name match for FILTER
    --list                 List benchmark names and exit
    --save-baseline <NAME> Save results as baseline NAME
    --baseline <NAME>      Compare against baseline NAME
    --threshold <PCT>      Regression threshold in percent [default: 5]
    --quick                Shorter, less precise run
    --noplot               Skip the HTML report
    --confidence <LEVEL>   Only 0.95 is supported
    -h, --help             Show this help
";

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_flags_and_filter() {
        let opts = Options::parse(["--quick", "--baseline", "main", "matrix", "--noplot"]).unwrap();
        assert!(opts.quick);
        assert!(opts.noplot);
        assert_eq!(opts.baseline.as_deref(), Some("main"));
        assert_eq!(opts.filter.as_deref(), Some("matrix"));
        assert_eq!(opts.threshold_pct, 5.0);
    }

    #[test]
    fn rejects_unknown_flags_and_bad_values() {
        assert!(Options::parse(["--bogus"]).is_err());
        assert!(Options::parse(["--baseline"]).is_err());
        assert!(Options::parse(["--threshold", "-1"]).is_err());
        assert!(Options::parse(["--confidence", "0.99"]).is_err());
    }

    #[test]
    fn ignores_cargo_bench_flag() {
        assert!(Options::parse(["--bench"]).is_ok());
    }

    #[test]
    fn filter_substring_and_exact() {
        let sub = Options::parse(["mul"]).unwrap();
        assert!(sub.selects("matrix::multiply"));
        let exact = Options::parse(["--exact", "multiply"]).unwrap();
        assert!(!exact.selects("matrix::multiply"));
        assert!(exact.selects("multiply"));
    }

    #[test]
    fn full_name_includes_group_when_present() {
        let run = |_: LayerKind, _: &Config| None;
        let grouped = BenchDef {
            group: "matrix",
            name: "multiply/128",
            layers: &[LayerKind::WallClock],
            run,
        };
        assert_eq!(grouped.full_name(), "matrix::multiply/128");
        let bare = BenchDef {
            group: "",
            ..grouped
        };
        assert_eq!(bare.full_name(), "multiply/128");
    }

    #[test]
    fn skipped_layers_are_omitted_from_results() {
        let run = |kind: LayerKind, _: &Config| match kind {
            LayerKind::WallClock => Some(crate::bencher::measure(
                &Config {
                    warmup: Duration::ZERO,
                    ..Config::default()
                },
                crate::wallclock::WallClock::with_clock(crate::clock::Clock::instant()),
                |b| b.iter(|| 1_u8),
            )),
            _ => None,
        };
        let def = BenchDef {
            group: "",
            name: "noop",
            layers: &[LayerKind::WallClock, LayerKind::HwInstructions],
            run,
        };
        let config = Config {
            warmup: Duration::ZERO,
            min_batch: Duration::from_micros(100),
            ..Config::default()
        };
        let results = run_benches(&[def], &config, None);
        assert_eq!(results.len(), 1);
        assert_eq!(results[0].layers.len(), 1);
        assert_eq!(results[0].layers[0].layer, "WallClock");
    }
}
